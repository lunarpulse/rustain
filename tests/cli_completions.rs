// ─── AC7(d): --bin-name default and override ───────────────────────────────

#[test]
fn bin_name_default_matches_clap_get_name() {
    let expected_name = Cli::command().get_name().to_string();
    let output = rustain_cmd()
        .args(["completions", "bash"])
        .output()
        .expect("failed to execute");
    assert!(output.status.success());
    let script = String::from_utf8_lossy(&output.stdout);

    // The bash script's function name uses the bin name as the root.
    // Structural marker: `_rustain()` function or `(rustain,` dispatch.
    assert!(
        script.contains(&format!("_{expected_name}()")),
        "default script must contain _{expected_name}() function marker"
    );
}

#[test]
fn bin_name_override_embeds_custom_name() {
    let output = rustain_cmd()
        .args(["completions", "bash", "--bin-name", "acme"])
        .output()
        .expect("failed to execute");
    assert!(output.status.success());
    let script = String::from_utf8_lossy(&output.stdout);

    // Structural marker: `_acme()` function for the custom bin name.
    assert!(
        script.contains("_acme()"),
        "overridden script must contain _acme() function marker"
    );
    // Must NOT contain the default name's root function.
    assert!(
        !script.contains("_rustain()"),
        "overridden script must NOT contain _rustain() function marker"
    );
}

