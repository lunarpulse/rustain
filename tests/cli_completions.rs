// ─── AC7(b): Derived-set + closure contract (bash) ─────────────────────────

#[test]
fn bash_completion_command_set_matches_clap() {
    let output = rustain_cmd()
        .args(["completions", "bash"])
        .output()
        .expect("failed to execute");
    assert!(output.status.success(), "exit code != 0");
    let script = String::from_utf8_lossy(&output.stdout);
    assert!(!script.is_empty(), "stdout must not be empty");

    let expected = expected_top_level();
    let actual = extract_bash_commands(&script);

    // Both directions: no missing command, no phantom command.
    let missing: BTreeSet<_> = expected.difference(&actual).collect();
    let phantom: BTreeSet<_> = actual.difference(&expected).collect();

    assert!(
        missing.is_empty(),
        "Commands in clap but NOT in bash script: {missing:?}"
    );
    assert!(
        phantom.is_empty(),
        "Commands in bash script but NOT in clap: {phantom:?}"
    );
    assert_eq!(expected, actual, "command sets must be identical");

    // Anti-vacuous: if clap_complete changes its bash output format and the
    // parser returns an empty set, the symmetric difference would still pass.
    // A non-empty guard forces the parser to actually match something.
    assert!(
        !actual.is_empty(),
        "bash parser found zero top-level commands — clap_complete output format may have changed"
    );
}
// ─── AC7(c): Per-shell light checks (zsh/fish/powershell) ─────────────────

// Structural self-name markers:
//   zsh: `#compdef <bin>`
//   fish: `complete -c <bin>`
//   powershell: `Register-ArgumentCompleter -Native -CommandName '<bin>'`
// These are chosen to avoid false-positives from help text / comments.
