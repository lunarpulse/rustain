// Broken-pipe handling differs by platform (Unix SIGPIPE vs Windows Err(BrokenPipe)).
#[cfg(unix)]
#[test]
fn broken_pipe_exits_cleanly() {
    use std::process::Stdio;
    // Run rustain directly in a pipeline with an early-closing reader so we can
    // inspect rustain's own exit status, not the outer `sh` pipeline's status.
    let bin = assert_cmd::cargo::cargo_bin("rustain");
    let mut rustain = std::process::Command::new(&bin)
        .args(["completions", "bash"])
        .stdout(Stdio::piped())
        .stderr(Stdio::piped())
        .spawn()
        .expect("failed to spawn rustain");

    let rustain_stdout = rustain.stdout.take().expect("rustain has no stdout");

    // Attach `head -n1` as the early-closing reader.
    let head = std::process::Command::new("head")
        .arg("-n1")
        .stdin(rustain_stdout)
        .stdout(Stdio::null())
        .stderr(Stdio::null())
        .output()
        .expect("failed to run head");
    assert!(head.status.success(), "head should exit 0");

    let output = rustain
        .wait_with_output()
        .expect("failed to wait for rustain");
    let stderr = String::from_utf8_lossy(&output.stderr);

    // Rustain must terminate cleanly: no panic text, no "failed printing" message,
    // and a non-error exit. On Unix with SIGPIPE reset to SIG_DFL, a broken pipe
    // terminates the process via signal 13 (exit code 141), which is the expected
    // clean behavior for a CLI tool.
    let clean_exit = output.status.success()
        || output.status.signal() == Some(libc::SIGPIPE)
        || output.status.code().is_none();
    assert!(
        clean_exit,
        "rustain must exit cleanly on broken pipe; got status {:?}, stderr: {stderr}",
        output.status
    );
    assert!(
        !stderr.contains("panic"),
        "broken pipe must not panic; stderr: {stderr}"
    );
    assert!(
        !stderr.contains("failed printing to stdout"),
        "broken pipe must not print 'failed printing to stdout'; stderr: {stderr}"
    );
}

// On Windows there is no SIGPIPE; rustain should return Ok(()) on Err(BrokenPipe).
#[cfg(not(unix))]
#[test]
fn broken_pipe_exits_cleanly() {
    use std::process::Stdio;
    let bin = assert_cmd::cargo::cargo_bin("rustain");
    let mut rustain = std::process::Command::new(&bin)
        .args(["completions", "bash"])
        .stdout(Stdio::piped())
        .stderr(Stdio::piped())
        .spawn()
        .expect("failed to spawn rustain");

    let rustain_stdout = rustain.stdout.take().expect("rustain has no stdout");
    let head = std::process::Command::new("powershell")
        .args(["-NoProfile", "-Command", "\u{0026} { process { break } }"])
        .stdin(rustain_stdout)
        .stdout(Stdio::null())
        .stderr(Stdio::null())
        .output()
        .expect("failed to run head");
    drop(head);

    let output = rustain
        .wait_with_output()
        .expect("failed to wait for rustain");
    let stderr = String::from_utf8_lossy(&output.stderr);
    assert!(
        output.status.success(),
        "rustain must exit 0 on broken pipe; got status {:?}, stderr: {stderr}",
        output.status
    );
    assert!(
        !stderr.contains("panic"),
        "broken pipe must not panic; stderr: {stderr}"
    );
    assert!(
        !stderr.contains("failed printing to stdout"),
        "broken pipe must not print 'failed printing to stdout'; stderr: {stderr}"
    );
}

// ─── AC7(g): Hidden-subcommand assertion ───────────────────────────────────

#[test]
fn hidden_subcommand_not_in_completions() {
    // `DaemonAction::__run` is `hide = true` (commands.rs). It must NOT appear
    // as a top-level completion. The daemon sub-subcommands are nested under
    // `daemon`, so `__run` appears as `rustain__daemon__run` if at all — but
    // crucially, `is_hide_set()` means the generator should exclude it.

    let output = rustain_cmd()
        .args(["completions", "bash"])
        .output()
        .expect("failed to execute");
    assert!(output.status.success());
    let script = String::from_utf8_lossy(&output.stdout);

    // The hidden `__run` should not have its own dispatch function in the script.
    // It would appear as `_rustain__daemon____run` or similar pattern if emitted.
    // Verify the expected set from clap does NOT include it:
    let hidden: Vec<_> = Cli::command()
        .get_subcommands()
        .filter(|c| c.is_hide_set())
        .map(|c| c.get_name().to_string())
        .collect();
    // There should be no hidden top-level commands currently.
    assert!(
        hidden.is_empty(),
        "unexpected hidden top-level commands: {hidden:?}"
    );

    // Check the daemon subcommand's hidden child `__run` specifically:
    let cmd = Cli::command();
    let daemon_cmd = cmd
        .get_subcommands()
        .find(|c| c.get_name() == "daemon")
        .expect("daemon subcommand must exist");
    let daemon_hidden: Vec<_> = daemon_cmd
        .get_subcommands()
        .filter(|c| c.is_hide_set())
        .map(|c| c.get_name().to_string())
        .collect();
    assert!(
        daemon_hidden.contains(&"__run".to_string()),
        "daemon __run must be hidden"
    );

    // Verify the bash script does NOT contain the hidden __run as a visible
    // completion option. In clap_complete bash output, hidden subcommands are
    // excluded from the case-arm dispatch.
    assert!(
        !script.contains("(rustain__daemon____run)"),
        "__run must not appear as a visible completion case-arm"
    );
}

// ─── Optional P1: bash -n syntax smoke ──────────────────────────────────────

/// Check whether `program --version` works; if not, print a clear message and
/// skip the syntax check. Using `eprintln!` + early return keeps the test green
/// on machines without the shell installed, while making the skip visible.
fn shell_available(program: &str) -> bool {
    let available = std::process::Command::new(program)
        .arg("--version")
        .output()
        .map(|o| o.status.success())
        .unwrap_or(false);
    if !available {
        eprintln!("{program} not available, skipping syntax check");
    }
    available
}

#[test]
fn zsh_syntax_check() {
    if !shell_available("zsh") {
        return;
    }

    let output = rustain_cmd()
        .args(["completions", "zsh"])
        .output()
        .expect("failed to generate zsh completions");
    assert!(output.status.success());

    // `zsh -n` parses the script without executing.
    let syntax_check = std::process::Command::new("zsh")
        .arg("-n")
        .stdin(std::process::Stdio::piped())
        .stdout(std::process::Stdio::piped())
        .stderr(std::process::Stdio::piped())
        .spawn()
        .and_then(|mut child| {
            use std::io::Write;
            child
                .stdin
                .take()
                .unwrap()
                .write_all(&output.stdout)
                .unwrap();
            child.wait_with_output()
        })
        .expect("failed to run zsh -n");

    assert!(
        syntax_check.status.success(),
        "zsh -n syntax check failed: {}",
        String::from_utf8_lossy(&syntax_check.stderr)
    );
}

