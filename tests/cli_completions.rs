//! Integration tests for `rustain completions <shell>` (Story 13.3b, FR104).
//!
//! AC7 guardrail tests: clap debug_assert, derived-set + closure contract (bash),
//! per-shell light checks, --bin-name override, invalid/missing shell rejection,
//! broken-pipe safety, and hidden-subcommand assertion.
//!
//! No `#[serial]` (no env/FS mutation). No `test-instrumentation` gate.

use std::collections::BTreeSet;
#[cfg(unix)]
use std::os::unix::process::ExitStatusExt;

use assert_cmd::Command;
use clap::CommandFactory;
use predicates::prelude::*;
use rustain::adapters::cli::commands::Cli;

fn rustain_cmd() -> Command {
    Command::cargo_bin("rustain").unwrap()
}

/// Derive the expected top-level command set from clap at test time.
/// Filters by the generator's visibility predicate: `!is_hide_set()`.
fn expected_top_level() -> BTreeSet<String> {
    Cli::command()
        .get_subcommands()
        .filter(|c| !c.is_hide_set())
        .map(|c| c.get_name().to_string())
        .collect()
}

/// Extract top-level subcommand names from the bash completion script.
///
/// Bash completions generated by clap_complete use `rustain,<cmd>)` case-arm
/// patterns in the command dispatch loop for top-level subcommands.
fn extract_bash_commands(script: &str) -> BTreeSet<String> {
    let mut cmds = BTreeSet::new();
    // In clap_complete 4.6.x, top-level subcommand dispatch uses case arms like:
    //   `rustain,ask)` → `cmd="rustain__subcmd__ask"`
    // We parse the `rustain,<name>)` patterns (one nesting level only).
    for line in script.lines() {
        let trimmed = line.trim();
        if let Some(rest) = trimmed.strip_prefix("rustain,") {
            if let Some(cmd) = rest.strip_suffix(')') {
                // Skip `help` (auto-generated by clap, not in our Command enum)
                // and `$1` (the root self-reference pattern).
                if cmd != "help" && !cmd.starts_with('$') {
                    cmds.insert(cmd.to_string());
                }
            }
        }
    }
    cmds
}

