const REGEN: &str =
    "RUSTAIN_WRITE_KEYMAP_DOC=1 cargo test --test tui conformance_21_3_keymap::k6_docs";

fn hosts_text(hosts: Hosts) -> &'static str {
    match hosts {
        Hosts::Both => "local, attached",
        Hosts::Local => "local",
        Hosts::Attached => "attached",
    }
}

fn reach_text(reach: Reach) -> &'static str {
    match reach {
        Reach::Portable => "portable",
        Reach::ExtendedKeyboard => "extended keyboard",
        Reach::AltMeta => "Alt (meta)",
        Reach::Unspecified => "unspecified",
    }
}

/// Where a row is `(n/a)`: narrow local terminals and the attached client.
fn availability_note(row: &Binding) -> String {
    let mut notes = Vec::new();
    if row.hosts.includes(Host::Local)
        && matches!(
            row.availability(&AvailCtx::local(80, DensityMode::Focus)),
            Availability::Unavailable(_)
        )
        && matches!(
            row.availability(&AvailCtx::local(130, DensityMode::Monitor)),
            Availability::Available
        )
    {
        notes.push("needs a terminal of 120+ columns");
    }
    if row.hosts.includes(Host::Attached)
        && let Availability::Unavailable(why) = row.availability(&AvailCtx::attached(130, false))
    {
        // A host-only limitation gets the host remedy; remaining legacy fields
        // retain their own explicitly declared no-cursor reason.
        let local = row.availability(&AvailCtx::local(130, DensityMode::Monitor));
        notes.push(if row.hosts.includes(Host::Local) && local.is_available() {
            "not available in an attached session"
        } else {
            why
        });
    }
    if !row.alt.is_empty() {
        return format!("portable alternative: {}", row.alt);
    }
    notes.join("; ")
}

/// Keys a context leaves out of the table on purpose (a named, documented exclusion).
fn exclusion(context: Context) -> Option<&'static str> {
    match context {
        Context::RecipientSurface => Some(
            "A writer's action keys (reply, accept, acknowledge, defer, share, decline, edit, use as context) depend on the received item and are listed in the view's own footer; they are not rows here.",
        ),
        _ => None,
    }
}

/// `docs/keyboard.md`, generated from the registry (all contexts, both hosts).
pub fn markdown_reference() -> String {
    if let Err(defects) = validate_rows(table()) {
        panic!("keymap table violates row governance: {defects:?}");
    }
    let mut out = String::new();
    let _ = writeln!(out, "# Keyboard reference\n");
    let _ = writeln!(
        out,
        "<!-- Generated by keymap::render_docs::markdown_reference(); do not edit by hand.\n     Regenerate: {REGEN} -->\n"
    );
    out.push_str(
        "Every key listed here comes from the keymap registry that also drives the keys, the `Ctrl+X` menu, the help overlay, the palette and the status row.\n\
`Ctrl+X` opens an untimed menu; press a follow-up key, or `Esc` to cancel. A follow-up with no binding answers with a notice instead of doing nothing.\n\
`Esc` and `Ctrl+C` never decide a decision card: they post one reminder of the keys that do and the card stays. Inline cards answer only in Chat focus, so typing in the composer never answers them. Blocking-card arrivals take Chat focus only from an empty Input; drafts and overlays keep focus. Transcript plan arrivals never take focus. Closing an attached overlay reconciles a pending approval, consent or consolidation card with an empty Input. An attached approval hidden by a draft remains counted in the status row; open the indicated decision route for guidance, clear the draft, then enter Chat to answer. A draft still hides that approval even in Chat.\n\
The attached client starts in Input in both writer and read-only modes. Its shared composer supports caret motions and readline editing, including Ctrl+A, Ctrl+E and Ctrl+K; read-only mode refuses submission, not local typing or local slash commands.\n\
Reach: *portable* keys work in every terminal; *extended keyboard* keys need a keyboard protocol most terminals lack; *Alt (meta)* keys depend on the terminal's Alt handling. Each non-portable key names a portable alternative.\n",
    );
    for context in Context::ALL {
        let rows: Vec<&Binding> = table().iter().filter(|r| r.context == context).collect();
        if rows.is_empty() {
            continue;
        }
        let _ = writeln!(out, "\n## {}\n", context.name());
        if !context.parents().is_empty() {
            let parents: Vec<&str> = context.parents().iter().map(|p| p.name()).collect();
            let _ = writeln!(out, "Also inherits: {}.\n", parents.join(", "));
        }
        if let Some(note) = exclusion(context) {
            let _ = writeln!(out, "{note}\n");
        }
        out.push_str("| Keys | Does | Hosts | Reach | Notes |\n|---|---|---|---|---|\n");
        for row in rows {
            let does = description(row).unwrap_or_else(|| {
                panic!("keymap row without a description reached the docs: {row:?}")
            });
            let _ = writeln!(
                out,
                "| `{}` | {} | {} | {} | {} |",
                row.long_label(),
                does.replace('|', "\\|"),
                hosts_text(row.hosts),
                reach_text(row.reach),
                availability_note(row).replace('|', "\\|"),
            );
        }
    }
    out
}

fn json_str(text: &str) -> String {
    serde_json::to_string(text).unwrap_or_else(|_| "\"\"".to_string())
}

/// `tests_tui/fixtures/keymap_portable_rows.json`: the portable rows the native
/// smoke sends as raw bytes (RU-22): leader follow-ups and any other portable
/// row that declares a smoke witness. One row per line.
pub fn portable_rows_json() -> String {
    let mut lines = Vec::new();
    for row in table().iter().filter(|r| r.reach == Reach::Portable) {
        let Some(bytes) = row.pty_bytes() else {
            continue;
        };
        if row.context != Context::Leader && row.witness.is_empty() {
            continue;
        }
        let hex: String = bytes.iter().map(|b| format!("{b:02x}")).collect();
        lines.push(format!(
            "    {{\"context\": {}, \"host\": {}, \"key\": {}, \"pty_hex\": \"{hex}\", \"witness\": {}}}",
            json_str(row.context.name()),
            json_str(hosts_text(row.hosts)),
            json_str(&row.long_label()),
            json_str(row.witness),
        ));
    }
    format!(
        "{{\n  \"generated_by\": \"keymap::render_docs::portable_rows_json\",\n  \"regenerate\": {},\n  \"rows\": [\n{}\n  ]\n}}\n",
        json_str(REGEN),
        lines.join(",\n")
    )
}

// ── docs truth lint ───────────────────────────────────────────────────────

static MODIFIED: LazyLock<Regex> =
    LazyLock::new(|| Regex::new(r"(?:Ctrl|Alt|Shift)\+(?:\w+|[?/\[\]])").expect("regex"));
static LEADER_SEQ: LazyLock<Regex> =
    LazyLock::new(|| Regex::new(r"Ctrl\+X(?:,\s?|\s)(Enter|Esc|\w\b|\?)").expect("regex"));
static COMPACT: LazyLock<Regex> =
    LazyLock::new(|| Regex::new(r"\^X (Enter|Esc|\w\b|\?)").expect("regex"));

/// The login overlay's own copy keys (`handlers::login`, live while a field is
/// focused): a modal surface outside the registry, named explicitly so the lint
/// still rejects every other key without a row.
const LOGIN_COPY_KEYS: &[&str] = &["alt+c", "alt+l", "alt+u"];
fn registry_tokens() -> (BTreeSet<String>, BTreeSet<String>) {
    let mut keys = BTreeSet::new();
    let mut follow_ups = BTreeSet::new();
    for row in table() {
        for key in row.keys {
            keys.insert(key.label().to_ascii_lowercase());
        }
        if row.context == Context::Leader {
            follow_ups.insert(sequence_label(Context::Leader, row.keys).to_ascii_lowercase());
        }
        if let Some(help) = row.help {
            keys.insert(help.key.to_ascii_lowercase());
        }
    }
    (keys, follow_ups)
}

/// Key tokens in `markdown` that no registry row backs (empty = the text is
/// true). Case-insensitive; `Ctrl+X, M`, `Ctrl+X M` and `^X m` are one token.
pub fn unresolved_key_tokens(markdown: &str) -> Vec<String> {
    let (keys, follow_ups) = registry_tokens();
    let mut bad = Vec::new();
    let mut check_follow_up = |raw: &str, token: String| {
        let trimmed = raw.trim_end_matches(|c: char| ",.;:)`".contains(c));
        let candidate = format!("ctrl+x, {}", trimmed.to_ascii_lowercase());
        if !follow_ups.contains(&candidate) {
            bad.push(token);
        }
    };
    for caps in LEADER_SEQ.captures_iter(markdown) {
        check_follow_up(&caps[1], caps[0].to_string());
    }
    for caps in COMPACT.captures_iter(markdown) {
        check_follow_up(&caps[1], caps[0].to_string());
    }
    for m in MODIFIED.find_iter(markdown) {
        let token = m.as_str().to_ascii_lowercase();
        if !keys.contains(&token) && !LOGIN_COPY_KEYS.contains(&token.as_str()) {
            bad.push(m.as_str().to_string());
        }
    }
    bad.sort();
    bad.dedup();
    bad
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn story21_3_reference_lists_every_context_and_the_lint_passes_on_it() {
        let doc = markdown_reference();
        assert!(doc.contains("`Ctrl+X, H`"), "{doc}");
        assert_eq!(unresolved_key_tokens(&doc), Vec::<String>::new());
    }

    #[test]
    fn story21_3_lint_rejects_a_retired_binding_and_accepts_a_true_one() {
        assert_eq!(
            unresolved_key_tokens("Ctrl+J toggles history"),
            vec!["Ctrl+J".to_string()]
        );
        assert!(unresolved_key_tokens("Press Ctrl+X, h or Ctrl+P to browse.").is_empty());
        assert_eq!(
            unresolved_key_tokens("use Ctrl+X, f"),
            vec!["Ctrl+X, f".to_string()]
        );
    }

    #[test]
    fn story21_3_fixture_rows_carry_pty_bytes_and_witnesses() {
        let json = portable_rows_json();
        let value: serde_json::Value = serde_json::from_str(&json).expect("valid json");
        let rows = value["rows"].as_array().expect("rows");
        assert!(
            rows.iter().any(|r| r["pty_hex"] == "1868"),
            "Ctrl+X h = 0x18 0x68"
        );
        assert!(
            rows.iter()
                .all(|r| r["pty_hex"].as_str().is_some_and(|h| h.starts_with("18")))
        );
    }
}
