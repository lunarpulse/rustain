/// Live reactivity payload derived from the canonical durable room event.
/// Persistence always goes through `NodeJournal`; this bus payload is never a
/// second writable store.
#[derive(Debug, Clone)]
pub enum DomainEventPayload {
    Room(crate::domain::models::RoomEvent),
}

impl From<crate::domain::models::RoomEvent> for DomainEventPayload {
    fn from(event: crate::domain::models::RoomEvent) -> Self {
        Self::Room(event)
    }
}

/// Tool progress event emitted by the bash adapter during long-running execution.
/// Story 16.9 — surfaced via the live rail + stdout tail in the render path.
#[derive(Debug, Clone)]
pub enum ToolProgressEvent {
    Counter { tool_use_id: String, k: u64, n: u64 },
    Tail { tool_use_id: String, text: String },
}

/// Action returned by apply_chunk() to tell the event loop what to do.
#[allow(dead_code)]
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum ChunkAction {
    /// No action needed.
    None,
    /// Trigger a redraw on next tick.
    NeedsRedraw,
    /// Turn is complete — persist and optionally generate title.
    TurnComplete {
        persist: bool,
        trigger_title_generation: bool,
    },
    /// Turn continues (tool use loop).
    TurnContinuing,
}
