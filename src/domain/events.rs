/// Domain-level application events flowing through the event loop.
/// crossterm types MUST NOT appear here — the adapter converts them to DomainInputEvent.
#[allow(dead_code)]
#[derive(Debug)]
pub enum AppEvent {
    /// Converted terminal input (crossterm → domain)
    InputEvent(DomainInputEvent),
    /// Streaming chunk from provider
    ProviderChunk {
        conversation_id: ConversationId,
        chunk: StreamChunk,
    },
    /// Tool execution result
    ToolResult(ToolResultEvent),
    /// Terminal resize
    Resize(u16, u16),
    /// Render tick
    Tick,
    /// Graceful shutdown request
    Shutdown,
    /// System notice (status bar messages).
    /// `conversation_id` routes the notice to a specific tab; `None` = global (show always).
    SystemNotice {
        conversation_id: Option<ConversationId>,
        level: NoticeLevel,
        message: String,
    },
    /// Internal domain events (legacy — kept for backward compat with 1.1a event loop)
    DomainEvent(DomainEventPayload),

    /// Change the active permission mode.
    SetPermissionMode(PermissionMode),
    /// Retry a message after backoff delay has elapsed.
    RetryMessage {
        conversation_id: ConversationId,
        content: String,
    },
    /// Title generated by background task.
    TitleGenerated {
        conversation_id: ConversationId,
        title: String,
    },
    /// Compaction completed successfully.
    CompactionComplete {
        conversation_id: ConversationId,
        summary: String,
        first_kept_message_id: Option<String>,
        pre_tokens: u32,
        purpose: CompactionPurpose,
    },
    /// Compaction failed.
    CompactionFailed {
        conversation_id: ConversationId,
        reason: String,
        purpose: CompactionPurpose,
    },
    /// AskUserQuestion tool call — display question card and send answer via oneshot.
    AskUserQuestion {
        conversation_id: ConversationId,
        tool_use_id: String,
        question: String,
        response_tx: tokio::sync::oneshot::Sender<String>,
    },
    /// Crash recovery prompt — display recovery FeedbackBlock on startup.
    RecoveryPrompt {
        conversation_id: ConversationId,
        title: String,
        token_count: u32,
    },

    /// Cross-search results ready from an async scan task (Story 4-4 AC5).
    /// Carries the original query so the event loop can discard stale results
    /// if the user has typed more characters in the meantime.
    /// No `conversation_id` — this is a view-update event per Amendment 3.
    CrossSearchResultsReady {
        query: String,
        results: Vec<CrossSearchResult>,
        truncated_by_count: bool,
        truncated_by_time: bool,
    },
    /// Peek highlight for a cross-search jump has expired (Story 4-4 AC6).
    /// Fired 1500 ms after the highlight was set by `OpenCrossSearchResult`.
    /// No `conversation_id` — view-update per Amendment 3. `tab_id` targets
    /// the specific tab whose peek highlight should clear.
    PeekHighlightExpired {
        tab_id: usize,
    },
    /// Skill discovery complete (Story 5-1 AC6).
    SkillsDiscovered {
        count: usize,
        warnings: usize,
    },
    /// Request to activate a skill (Story 5-2 AC8/AC9).
    AskActivateSkill {
        conversation_id: ConversationId,
        name: String,
        arguments: String,
    },
    /// Skill trust prompt for workspace-tier skills (Story 5-2 AC4).
    /// Event loop creates oneshot, TUI displays prompt, user responds y/n/i.
    ///
    /// Contract: consumers awaiting `response_tx` MUST treat `RecvError`
    /// (sender dropped without send — TUI shutdown / panic) as an implicit
    /// `Declined` with an Info-level feedback block, NOT as a silent hang.
    SkillTrustPrompt {
        skill_name: String,
        skill_file: std::path::PathBuf,
        response_tx: tokio::sync::oneshot::Sender<SkillTrustResponse>,
    },
    /// Completes a user-driven skill activation after the user responds to the
    /// trust prompt (Story 5-2 deadlock fix). Emitted by Branch 1's
    /// `SkillTrustAccept`/`SkillTrustDecline` handlers; consumed by Branch 2.
    ///
    /// `trusted: false` means the user declined — Branch 2 emits a decline
    /// notice and does nothing else.
    CompleteSkillActivation {
        conversation_id: ConversationId,
        skill_name: String,
        skill_file: std::path::PathBuf,
        arguments: String,
        trusted: bool,
    },
    AgentsDiscovered {
        count: usize,
        warnings: usize,
    },
    AgentThenSubmit {
        conversation_id: ConversationId,
        text: String,
        synthetic: bool,
    },
    /// Bridge event: a `ToolCallTransition` has been received on the broadcast
    /// channel and should be forwarded to the event loop for TUI/state updates.
    ToolCallTransitionBridged {
        conversation_id: ConversationId,
        transition: crate::domain::models::ToolCallTransition,
    },
    /// Bridge event: an `ApprovalRuntimeEvent` has been received on the broadcast
    /// channel and should be forwarded to the event loop for TUI/state updates.
    ApprovalRuntimeEventBridged {
        event: crate::domain::services::approval_runtime::ApprovalRuntimeEvent,
    },

    /// Story 7.6 AC8 — fired by the discovery background task on successful catalog refresh.
    /// The event-loop handler sets needs_redraw = true.
    ProviderCatalogRefreshed {
        provider_id: String,
    },

    /// Plan mode exit requested — present the plan approval card to the user.
    PlanApprovalRequested {
        conversation_id: ConversationId,
        plan_path: std::path::PathBuf,
        contents: String,
        summary: String,
    },
    /// Plan approval resolved by the user.
    PlanApprovalResolved {
        conversation_id: ConversationId,
        outcome: crate::domain::models::PlanApprovalOutcome,
    },

    PlanProposed {
        conversation_id: ConversationId,
        plan: crate::domain::models::Plan,
    },
    PlanCardResolved {
        conversation_id: ConversationId,
        plan_id: String,
        decision: crate::domain::models::PlanDecision,
    },
    PlanCardEditCompleted {
        conversation_id: ConversationId,
        plan_id: String,
        edited_plan: Option<crate::domain::models::Plan>,
    },

    /// Story 11.2a — `/memory consolidate` background sub-turn proposed durable
    /// facts to promote. The event-loop handler stores a `PendingConsolidationCard`
    /// (mirrors the `PlanProposed` → `pending_plan_card` grammar).
    MemoryConsolidationProposed {
        conversation_id: ConversationId,
        proposals: Vec<crate::domain::models::MemoryFact>,
    },
    /// Story 11.2a — the user resolved the consolidation card. `accepted` is the
    /// subset to promote via `remember_fact` (empty = declined; writes nothing).
    MemoryConsolidationResolved {
        conversation_id: ConversationId,
        accepted: Vec<crate::domain::models::MemoryFact>,
    },
    /// Story 11.2a — consolidation produced nothing / failed / timed out (AC6).
    /// The handler surfaces a `SystemNotice`; no card, no write.
    MemoryConsolidationFailed {
        conversation_id: ConversationId,
        reason: String,
    },
    /// Story 11.4a (AC-R0) — the user resolved the `/memory forget` confirm card.
    /// `keys` is the subset of stable `u64` content keys to permanently purge
    /// (empty = cancelled; purges nothing). The handler calls `MemoryPort::forget`,
    /// which writes a durable `RedactionRecord` per key and purges the index.
    MemoryForgetResolved {
        conversation_id: ConversationId,
        keys: Vec<u64>,
    },
    /// Plan-time delegation suggestion — present the modal card. Emitted by
    /// `PlanRuntime::on_task_dispatch` BEFORE flipping the task to Running,
    /// only when `DelegationDecider::suggest()` returns `Some(s)` with
    /// `s.auto_proceed == false`.
    PlanTaskDelegationRequested {
        conversation_id: ConversationId,
        plan_id: String,
        task_number: u32,
        suggestion: crate::domain::services::delegation_decider::DelegationSuggestion,
    },
    /// User (or YOLO short-circuit) resolved the delegation card.
    PlanTaskDelegationResolved {
        conversation_id: ConversationId,
        plan_id: String,
        task_number: u32,
        decision: DelegationDecision,
        agent_name: String,
    },
    /// Runtime-internal bridge: spool-tail-reader task → event-loop
    /// `on_turn_complete` call site.  Holds `TaskTurnOutcome` by value
    /// because `&mut Conversation` cannot cross a detached `tokio::spawn`.
    PlanTaskDelegationCompleted {
        conversation_id: ConversationId,
        plan_id: String,
        task_number: u32,
        outcome: crate::domain::services::plan_runtime::TaskTurnOutcome,
    },

    PlanExecutionStarted {
        conversation_id: ConversationId,
        plan_id: String,
    },
    /// Per-task status update — fired by PlanRuntime on each transition (Pending → Running,
    /// Running → Completed/Failed/Skipped/Cancelled, etc.). Story 6.3's task panel
    /// subscribes to this for real-time render.
    PlanTaskStatusChanged {
        conversation_id: ConversationId,
        plan_id: String,
        task_number: u32,
        status: crate::domain::models::PlanTaskStatus,
    },
    /// All tasks terminal; unified summary has been appended to the conversation.
    PlanCompleted {
        conversation_id: ConversationId,
        plan_id: String,
        completed: u32,
        failed: u32,
        skipped: u32,
        total_elapsed_ms: i64,
    },
    /// Plan execution was interrupted by a Cancelled task (AC2 hard-stop branch).
    /// 6.4 will additionally emit this on user-initiated `!cancel-plan`.
    PlanCancelled {
        conversation_id: ConversationId,
        plan_id: String,
        /// Task that triggered the cancel; None for whole-plan cancel from 6.4 user action.
        cancelled_at_task: Option<u32>,
    },
    /// Story 8.1 AC-10 — emitted by SIGHUP handler, /config reload slash command,
    /// and (in future) `rustain config reload` cross-process IPC. The handler
    /// reloads the layered config chain and atomically swaps the active AppConfig.
    ConfigReload,
    /// Story 8.1 AC-15 — result of a config reload, emitted by the handler after
    /// the reload succeeds or fails. Carries the actual outcome so telemetry
    /// subscribers receive truthful data (not hardcoded success).
    ConfigReloaded {
        success: bool,
        error: Option<String>,
    },
    /// Story 8.4 — emitted by handle_profile_switch_requested (sync) or its spawned
    /// continuation (async) on success. The TUI dispatch arm updates state.active_profile
    /// + emits a SystemNotice.
    ProfileSwitched {
        profile_name: String,
        identity_color: ProfileIdentityColor,
        summary: String,
        warm_cold_pending: bool,
    },
    /// Story 8.4 — emitted on swap failure (hot-phase rejection or warm
    /// post_transition_verify fail). Carries enough info for the dispatch arm to
    /// render the rollback message.
    ProfileSwitchFailed {
        profile_name: String,
        error: String,
        rolled_back: bool,
    },
    /// Story 8.5 — emitted by handle_apply_adapter_override on success.
    SessionAdapterOverridden {
        port: crate::domain::models::PortDimension,
        adapter_name: String,
        previous_adapter_name: String,
    },
    /// Story 8.5 — emitted on factory error during override application.
    SessionAdapterOverrideFailed {
        port: crate::domain::models::PortDimension,
        requested_adapter: String,
        error: String,
    },
    /// Story 6.4: emitted when the executing plan deviates from the approved plan
    /// (auto-skip of blocked tasks; agent-proposed revision deferred to 6.4-FU1).
    /// TUI renders a PlanDeviationCard requiring reapproval in Normal/Plan modes;
    /// YOLO mode auto-continues with a notice.
    PlanDeviation {
        conversation_id: ConversationId,
        plan_id: String,
        deviation_kind: crate::domain::models::plan::PlanDeviationKind,
        original_step_count: u32,
        current_step_count: u32,
        changed_steps: Vec<u32>,
        summary: String,
    },
    /// Story 9.1 — MCP server connection state changed.
    /// Emitted by `McpClientAdapter::connect`, `disconnect`, and reconnect tasks.
    /// The event loop sets `needs_redraw = true` so the Adapter Status panel
    /// picks up the new state on the next render tick (pull-based model).
    McpConnectionStateChanged {
        server_id: String,
        state: crate::domain::models::McpConnectionState,
        source_profile: Option<String>,
    },
    McpCatalogChanged {
        server_id: String,
        tool_count: usize,
    },
    /// Story 9.3a — capability lifecycle events from the CapabilityRegistry.
    /// Wraps the three sub-variants (Registered, Deregistered, Updated) in one
    /// nested enum to keep the top-level surface lean and group related events
    /// for the event_loop dispatcher.
    CapabilityEvent(CapabilityEvent),
    /// Story 14.4 — child→parent subagent event wrapped with attribution.
    /// The inner event is deliberately narrow; full AppEvent recursion is not allowed.
    Subagent(crate::domain::models::SubagentEnvelope),
    /// Story 14.3 — a fork-join wave started fanning out (14.3a seam).
    ForkJoinStarted {
        coordinator: crate::domain::models::AgentId,
        spoke_count: usize,
    },
    /// Story 14.3 — one spoke reached a terminal state.
    SpokeCompleted {
        agent_id: crate::domain::models::AgentId,
        label: String,
    },
    /// Story 14.3 — the grounded synthesis floor is ready (honest_empty set
    /// when zero spokes contributed signal — the cruelest-lie guard, AC7).
    SynthesisReady {
        coordinator: crate::domain::models::AgentId,
        honest_empty: bool,
    },
    /// Story 14.3 — a wave was cancelled (cancel-all wired; 14.3a surfaces it).
    WaveCancelled {
        coordinator: crate::domain::models::AgentId,
        killed: usize,
    },
    /// Story 14.3a (F1+F2+F5) — the wave handle is ready after the detached
    /// `tokio::spawn`. The event loop stores this in `TuiState.wave_run`.
    /// `Arc` (not `Box`) because `AppEvent` derives `Debug` and `Box<dyn _>`
    /// is not `Clone` — both engineers conceded in Preflight #2.
    WaveRunReady(std::sync::Arc<dyn crate::domain::ports::wave_handle::WaveHandle>),
    /// Story 14.3a (AC11) — emitted SYNCHRONOUSLY in the `r` handler BEFORE
    /// awaiting the rerun future. The cell shows "Re-running spoke {i}…" with
    /// prior content retained + dimmed (never blank). Counter UNCHANGED.
    SpokeRerunStarted {
        slot: usize,
    },
    /// Story 14.3a (AC11) — rerun terminal (Reverted or error). Clears the
    /// in-progress lamp for the slot. On Replaced, the lamp is cleared by
    /// the WaveRunReady handler instead.
    SpokeRerunReverted {
        slot: usize,
    },
    /// Story 14.3a (AI-12.3 D-B) — the wave task ended WITHOUT producing a
    /// handle (run_wave returned Err, or the spawn task panicked/was cancelled).
    /// Carries the spawn's `wave_id` so the handler correlates retire against the
    /// LIVE marker — a STALE late delivery (older wave's terminal after a newer
    /// spawn) is a no-op and can't retire a live marker. The event loop uses this
    /// to retire the in-flight marker so a stale `wave_cancel` never swallows a
    /// later Ctrl-C.
    WaveTerminated {
        id: u64,
    },
    /// Story 14.3a (AI-12.3 — Amelia) — a rerun was REJECTED because a rerun is
    /// already in flight for a spoke (the single-slot lamp can't represent two).
    /// Distinct from a generic SystemNotice so AC11 orphan/starvation is
    /// observable + testable (the cap-reject path emits THIS, not a silent drop,
    /// so a busy-loop on `r` can't starve the rerun outcome).
    RerunRejectedBusy {
        slot: usize,
    },
}

/// User decision for a delegation suggestion (AC-10-5-3).
/// Emitted by the TUI modal card (`[d]` Delegate / `[l]` Run locally).
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum DelegationDecision {
    /// Spawn the suggested agent and dispatch the task to it.
    Delegate,
    /// Skip delegation; fall through to local sequential execution.
    RunLocally,
}

/// Capability lifecycle events emitted by the CapabilityRegistry.
///
/// Flows through the existing `AppEvent` bus (NO new EventBus channel —
/// the registry's `event_tx` is injected from `ComposeContext.domain_tx`
/// per Epic 9 Flag 1).
#[derive(Debug, Clone, serde::Serialize, serde::Deserialize)]
pub enum CapabilityEvent {
    /// A new capability has been registered.
    Registered {
        capability: crate::domain::models::capability_registry::RegisteredCapability,
    },
    /// A capability has been deregistered.
    Deregistered {
        capability: crate::domain::models::capability_registry::RegisteredCapability,
    },
    /// An existing capability has been updated (same id, new data).
    Updated {
        id: crate::domain::models::capability_id::CapabilityId,
        old: crate::domain::models::capability_registry::RegisteredCapability,
        new: Box<crate::domain::models::capability_registry::RegisteredCapability>,
    },
}

